"""
Write the options table of README.md from PyToF.options.Options.describe().

Run `python -m tests.make_readme` after changing an option, its default or its
description; tests/test_readme.py fails while the README is out of date. The
table sits between the two marker comments in the README.
"""

from pathlib import Path

from PyToF.options import Options

README = Path(__file__).resolve().parents[1] / "README.md"
START = "<!-- options:start (generated by tests/make_readme.py) -->"
END = "<!-- options:end -->"


def updated(text):
    """README text with the table between the markers regenerated."""

    head, rest = text.split(START, 1)
    _, tail = rest.split(END, 1)
    return f"{head}{START}\n\n{Options.describe()}\n\n{END}{tail}"


def main():
    text = README.read_text()
    README.write_text(updated(text))
    print(f"updated the options table in {README}")


if __name__ == "__main__":
    main()
